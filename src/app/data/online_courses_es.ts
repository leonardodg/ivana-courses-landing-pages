const SKIP_KEYS = new Set(['src', 'href', 'slug', 'path', 'sku', 'price', 'kind', 'type', 'title_meta', 'desc']);

const walk = (v: unknown, key?: string, inReviews = false): unknown => {
  if (typeof v === 'string') return key && SKIP_KEYS.has(key) ? v : (ES[v] ?? v);
  if (Array.isArray(v)) return v.map((x) => walk(x, key, inReviews));
  if (v && typeof v === 'object') {
    const o = v as Record<string, unknown>;
    const reviews = o.type === 'reviews';
    return Object.fromEntries(
      Object.entries(o).map(([k, x]) => [k, reviews && k === 'items' ? x : walk(x, k, inReviews)]),
    );
  }
  return v;
};

/** Curso no idioma da página. Os depoimentos reais ficam no idioma original. */
export const localizeOnline = (c: OnlineCourse, l: 'pt' | 'es'): OnlineCourse => (l === 'es' ? (walk(c) as OnlineCourse) : c);
